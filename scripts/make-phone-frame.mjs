// Turns the flat iPhone mockup (images/phone_14_01.jpg) into a transparent frame overlay:
// background and screen become transparent, then the screen hole is measured so screenshots can sit behind it.
// Usage: node scripts/make-phone-frame.mjs
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const SRC = "images/phone_14_01.jpg";
const OUT = "public/frames/iphone-14-pro.png";
const META = "src/data/phoneFrame.ts";
const OUT_HEIGHT = 1100;

const { data, info } = await sharp(SRC).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const { width: W, height: H } = info;
const px = (x, y) => (y * W + x) * 4;

function flood(seedX, seedY, match) {
  const seen = new Uint8Array(W * H);
  const stack = [seedY * W + seedX];
  while (stack.length) {
    const i = stack.pop();
    if (seen[i]) continue;
    seen[i] = 1;
    const x = i % W, y = (i / W) | 0;
    const o = i * 4;
    if (!match(data[o], data[o + 1], data[o + 2])) { seen[i] = 2; continue; }
    if (x > 0) stack.push(i - 1);
    if (x < W - 1) stack.push(i + 1);
    if (y > 0) stack.push(i - W);
    if (y < H - 1) stack.push(i + W);
  }
  return seen; // 1 = filled, 2 = boundary
}

// Background: light grey, sampled from the corner.
const [br, bg, bb] = [data[0], data[1], data[2]];
const bgFill = flood(0, 0, (r, g, b) => Math.abs(r - br) + Math.abs(g - bg) + Math.abs(b - bb) < 36);
// Screen: near-white, seeded at the centre.
const scFill = flood(W >> 1, H >> 1, (r, g, b) => r > 200 && g > 200 && b > 200);

let minX = W, minY = H, maxX = 0, maxY = 0; // phone bounds
let sMinX = W, sMinY = H, sMaxX = 0, sMaxY = 0; // screen bounds
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    const i = y * W + x;
    if (scFill[i] === 1) {
      data[i * 4 + 3] = 0;
      if (x < sMinX) sMinX = x; if (x > sMaxX) sMaxX = x;
      if (y < sMinY) sMinY = y; if (y > sMaxY) sMaxY = y;
    } else if (bgFill[i] === 1) {
      data[i * 4 + 3] = 0;
    } else if (y < H * 0.93) { // ignore the drop shadow under the phone
      if (x < minX) minX = x; if (x > maxX) maxX = x;
      if (y < minY) minY = y; if (y > maxY) maxY = y;
    }
  }
}
// Soften the anti-aliased white fringe just outside the screen hole.
for (let y = sMinY - 3; y <= sMaxY + 3; y++) {
  for (let x = sMinX - 3; x <= sMaxX + 3; x++) {
    const o = px(x, y);
    if (data[o + 3] && data[o] > 120 && data[o + 1] > 120 && data[o + 2] > 120) data[o + 3] = 0;
  }
}

const cw = maxX - minX + 1, ch = maxY - minY + 1;
const scale = OUT_HEIGHT / ch;
await sharp(data, { raw: { width: W, height: H, channels: 4 } })
  .extract({ left: minX, top: minY, width: cw, height: ch })
  .resize({ height: OUT_HEIGHT })
  .png({ compressionLevel: 9 })
  .toFile(OUT);

const r = (n) => Math.round(n * 10000) / 10000;
const meta = {
  aspect: r(cw / ch),
  // screen hole as fractions of the frame image
  screen: {
    left: r((sMinX - minX) / cw),
    top: r((sMinY - minY) / ch),
    width: r((sMaxX - sMinX + 1) / cw),
    height: r((sMaxY - sMinY + 1) / ch),
  },
};
writeFileSync(
  META,
  `// Generated by scripts/make-phone-frame.mjs. Do not edit by hand.\n` +
    `export const phoneFrame = {\n  src: "/frames/iphone-14-pro.png",\n  aspect: ${meta.aspect},\n` +
    `  screen: { left: ${meta.screen.left}, top: ${meta.screen.top}, width: ${meta.screen.width}, height: ${meta.screen.height} },\n} as const;\n`
);
console.log({ W, H, phone: [minX, minY, cw, ch], screen: [sMinX, sMinY, sMaxX, sMaxY], out: [Math.round(cw * scale), OUT_HEIGHT], meta });
